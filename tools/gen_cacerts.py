#!/usr/bin/env python3
"""Writes src/cacerts.c: the root certificates the update check trusts (GitHub and the hosts it serves release files from).

The roots are taken from Mozilla's list as shipped in the Python `certifi` package:
    pip install certifi && python3 tools/gen_cacerts.py
Only the few families GitHub's servers chain to are included (about 20 of the ~140 roots) to keep the program small.
"""
import re, ssl, sys, base64, hashlib
import certifi

WANT = [
    "USERTrust ECC Certification Authority", "USERTrust RSA Certification Authority", "AAA Certificate Services",
    "Sectigo Public Server Authentication Root R46", "Sectigo Public Server Authentication Root E46",
    "COMODO ECC Certification Authority", "COMODO RSA Certification Authority",
    "DigiCert Global Root CA", "DigiCert Global Root G2", "DigiCert Global Root G3",
    "DigiCert TLS ECC P384 Root G5", "DigiCert TLS RSA4096 Root G5", "DigiCert High Assurance EV Root CA",
    "ISRG Root X1", "ISRG Root X2",
    "GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4",
    "Amazon Root CA 1", "Amazon Root CA 2", "Amazon Root CA 3", "Amazon Root CA 4",
    "Starfield Services Root Certificate Authority - G2",
    "Microsoft RSA Root Certificate Authority 2017", "Microsoft ECC Root Certificate Authority 2017",
    "GlobalSign Root CA - R3", "GlobalSign Root R46", "GlobalSign Root E46",
    "Baltimore CyberTrust Root",
]

pem = open(certifi.where(), encoding="ascii").read()
found = {}
for chunk in pem.split("-----END CERTIFICATE-----"):
    if "-----BEGIN CERTIFICATE-----" not in chunk: continue
    head, body = chunk.split("-----BEGIN CERTIFICATE-----")
    m = re.search(r'^# Label: "?(.*?)"?$', head, re.M)
    if m and m.group(1).strip() in WANT:
        found[m.group(1).strip()] = base64.b64decode("".join(body.split()))
missing = [w for w in WANT if w not in found]
if missing: print("not in this certifi (skipped):", ", ".join(missing), file=sys.stderr)

out = ["/* Generated by tools/gen_cacerts.py from Mozilla's root list (python certifi). Do not edit. */",
       '#include "cacerts.h"', ""]
for i, (label, der) in enumerate(found.items()):
    out.append("/* %s - SHA-256 %s */" % (label, hashlib.sha256(der).hexdigest()))
    out.append("static const unsigned char r%d[%d] = {" % (i, len(der)))
    for k in range(0, len(der), 16):
        out.append("    " + ", ".join("0x%02x" % b for b in der[k:k+16]) + ",")
    out.append("};")
out.append("")
out.append("const ls_ca_root ls_ca_roots[] = {")
for i, label in enumerate(found):
    out.append('    { r%d, sizeof r%d, "%s" },' % (i, i, label))
out.append("};")
out.append("const int ls_ca_roots_n = %d;" % len(found))
open("src/cacerts.c", "w").write("\n".join(out) + "\n")
print("wrote src/cacerts.c with %d roots" % len(found))
