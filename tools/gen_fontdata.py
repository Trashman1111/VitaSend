#!/usr/bin/env python3
# Author: trashman (VitaSend)
"""
gen_fontdata.py - builds src/fontdata.c (the fonts that are compiled into the app).

You do NOT need to run this to build the app: src/fontdata.c is part of the project.
It is only here to show where the data comes from (and to regenerate it).

    pip install fonttools
    python3 tools/gen_fontdata.py  [--poppins DIR] [--liberation DIR]

Fonts (both under the SIL Open Font License 1.1, see fonts/LICENSES.txt):
  * Poppins Regular / Medium / Bold   - Latin only. This is the font the LocalSend desktop app looks like.
  * Liberation Sans Regular / Bold    - covers Latin, Greek, Cyrillic: used for every character Poppins lacks.
They are cut down to the characters we need and renamed (the OFL asks for that when a font is modified).
"""
import argparse, os, sys, io
from fontTools import subset
from fontTools.ttLib import TTFont

ap = argparse.ArgumentParser()
ap.add_argument("--poppins", default="/usr/share/fonts/truetype/google-fonts")
ap.add_argument("--liberation", default="/usr/share/fonts/truetype/liberation")
args = ap.parse_args()
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "fontdata.c")
OUTH = os.path.join(HERE, "..", "src", "fontdata.h")

def rng(a, b): return list(range(a, b + 1))
LATIN = rng(0x20, 0x7E) + rng(0xA0, 0x17F) + [0x18F, 0x192, 0x1A0, 0x1A1, 0x1AF, 0x1B0, 0x218, 0x219, 0x21A, 0x21B]
PUNCT = rng(0x2010, 0x2027) + [0x2030, 0x2039, 0x203A, 0x20AC, 0x2122, 0x2212, 0x2022]
ARROWS = rng(0x2190, 0x2193)
GREEK = rng(0x370, 0x3FF)
CYR = rng(0x400, 0x4FF)
MISC = [0x25CF, 0x25CB, 0x2713, 0x2717, 0x2605, 0x2606, 0xFFFD]

FONTS = [
    # (C name, source file, codepoints, new family name, style)
    ("poppins_regular", "Poppins-Regular.ttf", LATIN + PUNCT, "LS Sans", "Regular"),
    ("poppins_medium",  "Poppins-Medium.ttf",  LATIN + PUNCT, "LS Sans Medium", "Regular"),
    ("poppins_bold",    "Poppins-Bold.ttf",    LATIN + PUNCT, "LS Sans Bold", "Regular"),
    ("fallback_regular", "LiberationSans-Regular.ttf", LATIN + PUNCT + ARROWS + GREEK + CYR + MISC, "LS Fallback", "Regular"),
    ("fallback_bold",    "LiberationSans-Bold.ttf",    LATIN + PUNCT + ARROWS + GREEK + CYR + MISC, "LS Fallback Bold", "Regular"),
]

def find(name):
    for d in (args.poppins, args.liberation):
        p = os.path.join(d, name)
        if os.path.exists(p): return p
    sys.exit("font not found: " + name)

def cut(path, cps, family, style):
    opts = subset.Options()
    opts.layout_features = []
    opts.hinting = False
    opts.notdef_outline = True
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    opts.glyph_names = False
    opts.drop_tables += ["DSIG", "GPOS", "GSUB", "GDEF", "kern", "hdmx", "VDMX", "LTSH", "fpgm", "prep", "cvt "]
    font = TTFont(path)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=sorted(set(cps)))
    sub.subset(font)
    name = font["name"]
    for rec in list(name.names):
        if rec.nameID in (1, 16): rec.string = family
        elif rec.nameID in (2, 17): rec.string = style
        elif rec.nameID == 4: rec.string = family
        elif rec.nameID == 6: rec.string = family.replace(" ", "")
        elif rec.nameID == 3: rec.string = family.replace(" ", "") + "-subset"
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()

with open(OUT, "w") as c, open(OUTH, "w") as h:
    c.write("/* Generated by tools/gen_fontdata.py - do not edit. Fonts: see fonts/LICENSES.txt (SIL OFL 1.1).\n *\n * Author: trashman (VitaSend)\n */\n#include \"fontdata.h\"\n\n")
    h.write("/* Generated by tools/gen_fontdata.py - do not edit. */\n#ifndef LS_FONTDATA_H\n#define LS_FONTDATA_H\n#include <stddef.h>\n\n")
    total = 0
    for cname, src, cps, family, style in FONTS:
        data = cut(find(src), cps, family, style)
        total += len(data)
        print(f"{cname:18s} {len(data):7d} bytes")
        h.write(f"extern const unsigned char font_{cname}[{len(data)}];\n#define FONT_{cname.upper()}_SIZE {len(data)}\n")
        c.write(f"const unsigned char font_{cname}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            c.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        c.write("};\n\n")
    h.write("\n#endif\n")
    print("total", total)
